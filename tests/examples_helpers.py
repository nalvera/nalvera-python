def write_nifti(path: Path, shape: Sequence[int] = (8, 8, 6), *, seed: int = 0,
                zooms: Sequence[float] = (1.5, 1.5, 2.0), descrip: bytes = b"",
                extension: Optional[bytes] = None, data: Any = None) -> Path:
    """A small NIfTI file (``.nii`` or ``.nii.gz`` by its name); each seed
    gives other voxels, so two files are never the same scan."""
    import nibabel as nib
    import numpy as np
    if data is None:
        data = np.random.default_rng(seed).integers(-1000, 1000, size=tuple(shape)).astype(
            np.int16)
    image = nib.Nifti1Image(data, np.diag([*zooms, 1.0]))
    image.header["descrip"] = descrip
    if extension is not None:
        image.header.extensions.append(nib.nifti1.Nifti1Extension(6, extension))
    path.parent.mkdir(parents=True, exist_ok=True)
    nib.save(image, str(path))
    return path


