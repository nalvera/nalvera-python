"""Helpers for tests/test_examples.py.

* ``comment_problems(path)``: checks every ``# default: …`` / ``# required…``
  / ``# Options: …`` comment of an example against the code (the signatures of
  the public functions, ``nalvera.SETTINGS``) and against what the fake server
  lists for a generation (which mirrors the real route).
* ``shell_comment_problems``: the same for the command-line examples, against
  the command parser.
* ``python_text_problems`` / ``command_line_text_problems``: the two
  interfaces kept apart (no command or option in a Python example or
  notebook, no Python call in a command-line example).
* ``cheatsheet()`` and ``settings_table()``: the generated parts of
  ``examples/command_line/cli_cheatsheet.md`` and ``examples/README.md``.
* ``manifest_with_examples()``: the list of examples in ``MANIFEST.in``.
* ``write_nifti`` / ``write_dicom``: the placeholder inputs the examples name.

``python tests/examples_helpers.py`` rewrites the generated files and parts.
"""
