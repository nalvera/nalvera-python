def budget_values() -> List[str]:
    from nalvera import budget
    return [budget.PERSONAL, "lab:<id>", budget.FREE, budget.ASK]


def calls() -> Dict[str, Callable]:
    """The public functions an example may call, by the name it is called by."""
    import nalvera
    import nalvera.anonymize as anonymize
    from nalvera import Client
    return {
        "login": nalvera.login, "logout": nalvera.logout, "scans": Client.scans,
        "save_anonymized": Client.save_anonymized,
        "Client": Client.__init__, "run": Client.run, "estimate_run": Client.estimate_run,
        "run_in_background": Client.run, "generate": Client.generate, "wait": Client.wait,
        "download": Client.download, "tasks": Client.tasks, "task": Client.task,
        "cancel": Client.cancel, "me": Client.me, "models": Client.models,
        "estimate": Client.estimate, "prepare": anonymize.prepare,
        "inspect": anonymize.inspect, "Mapping": anonymize.Mapping.__init__,
        "find": anonymize.Mapping.find,
    }


def signature(function: Callable) -> Dict[str, inspect.Parameter]:
    return {name: p for name, p in inspect.signature(function).parameters.items()
            if name != "self" and p.kind not in (p.VAR_KEYWORD, p.VAR_POSITIONAL)}


def parser() -> argparse.ArgumentParser:
    from nalvera import cli
    return cli.build_parser()


def subparsers(top: Optional[argparse.ArgumentParser] = None) -> Dict[str, argparse.ArgumentParser]:
    top = top or parser()
    for action in top._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def cli_default_word(action: argparse.Action) -> str:
    """How an example's comment names a command-line option's default."""
    if action.default is None or action.default == []:
        return "none"
    if action.default is False:
        return "off"
    return str(action.default)


def setting_names() -> List[str]:
    import nalvera
    return [s.name for s in nalvera.SETTINGS]


# ── Reading comments ──────────────────────────────────────────────────────────
@dataclass
class Comment:
    line: int
    text: str                       # without "#", continuation lines joined
    kind: str                       # "default" or "required"
    default: str
    options: str


_LITERAL_RX = re.compile(r"""\s*(None|True|False|-?\d+(?:\.\d+)?|"[^"]*"|'[^']*'|\[[^\]]*\])""")


def _split(text: str) -> Optional[Comment]:
    text = text.strip()
    if text.startswith("default:"):
        kind, rest = "default", text[len("default:"):]
    elif re.match(r"required\b", text):
        kind, rest = "required", text[len("required"):]
    else:
        return None
    match = re.search(r"\b(?:Options|See):", rest)
    default, options = (rest[:match.start()], rest[match.end():]) if match else (rest, "")
    return Comment(0, text, kind, default.strip().rstrip(".").strip(), options.strip())


def python_comments(source: str) -> List[Comment]:
    """The checked comments of Python source, each on the line of the code it
    follows; a comment-only line in the same column continues it."""
    code_lines, raw = set(), []
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            raw.append((tok.start[0], tok.start[1], tok.string[1:].strip()))
        elif tok.type not in (tokenize.NL, tokenize.NEWLINE, tokenize.INDENT,
                              tokenize.DEDENT, tokenize.ENDMARKER):
            code_lines.update(range(tok.start[0], tok.end[0] + 1))
    out: List[Comment] = []
    block: Optional[Dict[str, Any]] = None        # the comment being continued
    for line, col, text in raw:
        if line in code_lines:
            block = {"start": line, "last": line, "col": col, "text": text}
        elif block is not None and col == block["col"] and line == block["last"] + 1:
            block["last"], block["text"] = line, block["text"] + " " + text
        else:
            block = None
            continue
        parsed = _split(block["text"])
        if parsed is None:
            continue
        parsed.line = block["start"]
        if out and out[-1].line == parsed.line:
            out[-1] = parsed
        else:
            out.append(parsed)
    return out


def literal(text: str) -> Tuple[bool, Any]:
    match = _LITERAL_RX.match(text)
    if not match:
        return False, None
    try:
        return True, ast.literal_eval(match.group(1))
    except (ValueError, SyntaxError):
        return False, None


def quoted(text: str) -> List[str]:
    return re.findall(r'"([^"]*)"', text)


def words(text: str) -> List[str]:
    return [w.strip() for w in re.split(r"[|,;]", text) if w.strip()]


def number_range(text: str) -> Optional[Tuple[float, float]]:
    match = re.search(r"(-?\d+(?:\.\d+)?) to (-?\d+(?:\.\d+)?)", text)
    return (float(match.group(1)), float(match.group(2))) if match else None


def commands_in(text: str) -> List[List[str]]:
    """``nalvera ...`` command lines inside a comment or a line of shell. A
    ``nalvera`` command inside a ``$(...)`` substitution is one of them (it
    comes first), and the substitution stands for a task id."""
    found = [c for inner in re.findall(r"\$\(([^)]*)\)", text) for c in commands_in(inner)]
    text = re.sub(r'"?\$\([^)]*\)"?', "TASK_ID", text)
    for match in re.finditer(r"(?<![\w./-])nalvera((?:[ \t]+[^\s#;|&`]+)+)", text):
        body = match.group(1).rstrip("\\").rstrip(".")
        try:
            found.append(shlex.split(body))
        except ValueError:
            found.append(body.split())
    return found


def markdown_commands(text: str) -> List[List[str]]:
    """The ``nalvera ...`` commands inside backticks of a Markdown file."""
    return [shlex.split(span) for span in re.findall(r"`nalvera ([^`]+)`", text)]


def command_problem(words_: List[str]) -> Optional[str]:
    """Why ``nalvera <words>`` would not parse, or None."""
    if not words_ or words_[0] in ("--help", "--version"):
        return None
    if words_[0] not in subparsers():
        return f"nalvera {' '.join(words_)}: unknown command"
    stderr = sys.stderr
    try:
        sys.stderr = io.StringIO()
        parser().parse_args(words_)
    except SystemExit as stop:
        if stop.code in (0, None):                   # --help of a command
            return None
        return f"nalvera {' '.join(words_)}: does not parse ({stop.code})"
    finally:
        sys.stderr = stderr
    return None


# ── The comment checker ───────────────────────────────────────────────────────
@dataclass
class _Setting:
    function: str
    name: str
    call: ast.Call
    params: Optional[Dict[str, ast.AST]] = None     # a generation setting: its params dict


def _call_name(node: ast.Call) -> Optional[str]:
    if isinstance(node.func, ast.Attribute):
        return node.func.attr
    if isinstance(node.func, ast.Name):
        return node.func.id
    return None


def _constants(tree: ast.AST) -> Dict[str, Any]:
    out = {}
    for node in getattr(tree, "body", []):
        if isinstance(node, ast.Assign) and len(node.targets) == 1 \
                and isinstance(node.targets[0], ast.Name):
            try:
                out[node.targets[0].id] = ast.literal_eval(node.value)
            except ValueError:
                pass
    return out


def _value(node: Optional[ast.AST], constants: Dict[str, Any]) -> Any:
    if node is None:
        return None
    if isinstance(node, ast.Name):
        return constants.get(node.id)
    try:
        return ast.literal_eval(node)
    except ValueError:
        return None


def _argument(call: ast.Call, name: str, position: int) -> Optional[ast.AST]:
    for kw in call.keywords:
        if kw.arg == name:
            return kw.value
    if len(call.args) > position:
        return call.args[position]
    return None


def settings_by_line(tree: ast.AST) -> Dict[int, List[_Setting]]:
    """Every keyword argument of a public call, and every key of a ``params``
    dict, by the line it starts on."""
    known = calls()
    out: Dict[int, List[_Setting]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or _call_name(node) not in known:
            continue
        function = _call_name(node)
        for kw in node.keywords:
            if kw.arg is None:
                continue
            if kw.arg == "params" and isinstance(kw.value, ast.Dict):
                keys = {k.value: v for k, v in zip(kw.value.keys, kw.value.values)
                        if isinstance(k, ast.Constant)}
                for key in kw.value.keys:
                    if isinstance(key, ast.Constant):
                        out.setdefault(key.lineno, []).append(
                            _Setting(function, key.value, node, keys))
                continue
            out.setdefault(kw.lineno, []).append(_Setting(function, kw.arg, node))
    return out


def comment_problems(name: str, source: str) -> List[str]:
    """What is wrong with the default/options comments of one Python example."""
    tree = ast.parse(source)
    constants = _constants(tree)
    settings = settings_by_line(tree)
    comments = {c.line: c for c in python_comments(source)}
    problems = []
    for line, found in sorted(settings.items()):
        if len(found) > 1:
            problems.append(f"{name}:{line}: one setting per commented line")
            continue
        setting = found[0]
        comment = comments.get(line)
        if comment is None:
            problems.append(f"{name}:{line}: {setting.name}= has no default/options comment")
            continue
        if (name, setting.name) in UNCHECKED:
            continue
        check = _check_generation if setting.params is not None else _check_argument
        problems += [f"{name}:{line}: {setting.name}: {p}"
                     for p in check(setting, comment, constants)]
    for line in sorted(set(comments) - set(settings)):
        problems.append(f"{name}:{line}: a default/options comment beside no setting")
    return problems


def _check_argument(setting: _Setting, comment: Comment, constants: Dict[str, Any]) -> List[str]:
    params = signature(calls()[setting.function])
    if setting.name not in params:
        return [f"not an argument of {setting.function}"]
    param = params[setting.name]
    problems = []
    if comment.kind == "required":
        if param.default is not inspect.Parameter.empty:
            problems.append(f"has a default ({param.default!r}), the comment says required")
    else:
        ok, value = literal(comment.default)
        if param.default is inspect.Parameter.empty:
            problems.append("is required, the comment names a default")
        elif not ok:
            problems.append(f"the default must start with its value: {comment.default!r}")
        elif value != param.default or type(value) is not type(param.default):
            problems.append(f"the comment says {value!r}, the code {param.default!r}")
    problems += _check_options(setting, comment, param, constants)
    return problems


def _check_options(setting: _Setting, comment: Comment, param: inspect.Parameter,
                   constants: Dict[str, Any]) -> List[str]:
    options, problems = comment.options, []
    for words_ in commands_in(options):
        problem = command_problem(words_)
        if problem:
            problems.append(problem)
        if setting.name == "task" and "--model" in words_:
            model = _value(_argument(setting.call, "model", 1), constants)
            listed = words_[words_.index("--model") + 1]
            if model != listed:
                problems.append(f"the options name the model {listed}, the call runs {model}")
    if not options:
        return problems
    if setting.name == "budget" and sorted(quoted(options)) != sorted(budget_values()):
        problems.append(f"budget options {quoted(options)} are not {budget_values()}")
    elif setting.name == "task" and setting.function == "generate":
        model = _value(_argument(setting.call, "model", 0), constants)
        listed = [t["id"] for m in fake_server.catalog_models() if m["id"] == model
                  for t in m["tasks"]]
        if sorted(quoted(options)) != sorted(listed):
            problems.append(f"tasks {quoted(options)} are not the catalog's {listed}")
    elif setting.name == "state" and quoted(options) != list(fake_server.TASK_LIST_STATES):
        problems.append(f"states {quoted(options)} are not {fake_server.TASK_LIST_STATES}")
    elif setting.name == "limit" and number_range(options) != tuple(
            float(n) for n in fake_server.TASK_LIST_LIMIT):
        problems.append(f"limit range is not {fake_server.TASK_LIST_LIMIT}")
    elif setting.name == "part" and not all(re.fullmatch(r"(image|mask)\d*", p)
                                            for p in quoted(options)):
        problems.append("parts are image, mask, image2, mask2, ...")
    elif "bool" in str(param.annotation) and "True" in options:
        if sorted(w for w in words(options) if w in ("True", "False")) != ["False", "True"]:
            problems.append("a yes/no option is True | False")
    return problems


def _check_generation(setting: _Setting, comment: Comment, constants: Dict[str, Any]) -> List[str]:
    task = _value(_argument(setting.call, "task", 1), constants)
    help_ = fake_server.generation_help(task or "")
    if help_ is None:
        return [f"no generation task {task!r}"]
    name, values = setting.name, setting.params or {}
    mode = _value(values.get("mode"), constants)
    problems = []
    required = name in fake_server.GENERATION_REQUIRED \
        or (task == "rflow-mr-brain" and name == "contrasts") \
        or (task == "rflow-ct" and mode == "image-mask" and name == "body_region")
    if comment.kind == "required":
        if not required:
            problems.append("the platform does not require it")
    else:
        ok, value = literal(comment.default)
        defaults = dict(help_["defaults"])
        if name in defaults:
            expected = defaults[name]
        elif name in fake_server.GENERATION_SCHEMA_DEFAULTS:
            expected = fake_server.GENERATION_SCHEMA_DEFAULTS[name]
        else:
            return [f"{name} has no default the platform names"]
        if not ok or value != expected:
            problems.append(f"the comment says {comment.default!r}, the platform {expected!r}")
    options = comment.options
    listed = {"mode": "modes", "contrasts": "contrasts", "body_region": "body_regions"}
    if name in listed:
        if sorted(quoted(options)) != sorted(help_[listed[name]]):
            problems.append(f"options {quoted(options)} are not {help_[listed[name]]}")
    elif name == "anatomy_list":
        regions = _value(values.get("body_region"), constants) or []
        allowed = help_["tumours_by_region"].get(regions[0], []) if regions else help_["tumours"]
        if not quoted(options) or not set(quoted(options)) <= set(allowed):
            problems.append(f"tumors {quoted(options)} are not among {allowed}")
    elif name == "skull_stripped":
        if sorted(w for w in words(options) if w in ("True", "False")) != ["False", "True"]:
            problems.append("skull_stripped is False | True")
    elif name == "output_size":
        xy = re.search(r"X from ([\d |]+)", options)
        z = re.search(r"Z from ([\d |]+)", options)
        if not xy or not z or [int(n) for n in re.findall(r"\d+", xy.group(1))] \
                != help_["xy_sizes"] or [int(n) for n in re.findall(r"\d+", z.group(1))] \
                != help_["z_sizes"]:
            problems.append(f"sizes are X from {help_['xy_sizes']}, Z from {help_['z_sizes']}")
    elif name == "spacing":
        if number_range(options) != (help_["spacing_mm"]["min"], help_["spacing_mm"]["max"]):
            problems.append(f"spacing is {help_['spacing_mm']}")
    elif name in SCHEMA_RANGES:
        if options and number_range(options) != tuple(float(n) for n in SCHEMA_RANGES[name]):
            problems.append(f"{name} is from {SCHEMA_RANGES[name]}")
    elif name not in fake_server.GENERATION_REQUIRED:
        problems.append(f"{name} is not a generation setting")
    return problems


# ── Shell, YAML and the notebook ──────────────────────────────────────────────
_OPTION_RX = re.compile(r"^\s*#\s*(--[a-z][a-z-]*)\s+default:\s*(.*)$")
_ENV_RX = re.compile(r"^\s*#\s*([A-Z][A-Z0-9_]+)\s+default:\s*(.*)$")
_CONTINUATION_RX = re.compile(r"^\s*#\s{3,}(\S.*)$")


def shell_comment_problems(name: str, text: str) -> List[str]:
    """The ``# --option  default: …`` and ``# NAME  default: …`` comments of a
    shell script or workflow, against the parser and ``nalvera.SETTINGS``."""
    lines = text.splitlines()
    problems = []
    for number, line in enumerate(lines):
        option, env = _OPTION_RX.match(line), _ENV_RX.match(line)
        if not option and not env:
            continue
        body = (option or env).group(2)
        follow = number + 1
        while follow < len(lines) and _CONTINUATION_RX.match(lines[follow]):
            body += " " + _CONTINUATION_RX.match(lines[follow]).group(1)
            follow += 1
        parsed = _split("default:" + body) or Comment(0, body, "default", body, "")
        where = f"{name}:{number + 1}"
        if env:
            setting = env.group(1)
            if setting not in setting_names():
                problems.append(f"{where}: {setting} is not a setting the package reads")
            if not parsed.default.startswith("unset"):
                problems.append(f"{where}: an environment default starts with 'unset'")
            if setting == "NALVERA_BUDGET" and sorted(words(parsed.options)) != \
                    sorted(budget_values()):
                problems.append(f"{where}: budget options are {budget_values()}")
            continue
        command = next((c for later in lines[follow:] if not later.strip().startswith("#")
                        for c in commands_in(later)), None)
        if not command or command[0] not in subparsers():
            problems.append(f"{where}: {option.group(1)} is above no nalvera command")
            continue
        sub = subparsers()[command[0]]
        action = next((a for a in sub._actions if option.group(1) in a.option_strings), None)
        if action is None:
            problems.append(f"{where}: nalvera {command[0]} has no {option.group(1)}")
            continue
        if not parsed.default.split(" ")[0].rstrip(".") == cli_default_word(action):
            problems.append(f"{where}: {option.group(1)} default is {cli_default_word(action)!r}")
        if option.group(1) == "--budget" and sorted(words(parsed.options)) != \
                sorted(budget_values()):
            problems.append(f"{where}: budget options are {budget_values()}")
    return problems


def shell_commands(text: str) -> List[List[str]]:
    """Every ``nalvera`` command line of a script, a workflow or a Markdown
    file, commented ones too, with backslash continuations joined."""
    joined = re.sub(r"\\\n\s*", " ", text)
    out = []
    for line in joined.splitlines():
        stripped = re.sub(r"^run:\s*", "", line.strip().lstrip("#").strip())
        if re.match(r"nalvera\s|[A-Za-z_][A-Za-z0-9_]*=\$\(nalvera\s", stripped):
            out += commands_in(stripped.split(" #")[0])
    return out


#: Install lines are the same in both interfaces.
_INSTALL_RX = re.compile(r"pip install[^\n]*")
_PY_CALL_RX = re.compile(r"\bnalvera\.\w+\(|\bimport nalvera\b")


def python_text_problems(name: str, text: str) -> List[str]:
    """A Python example or notebook names no ``nalvera`` command and no
    ``--option`` (install lines excepted)."""
    clean = _INSTALL_RX.sub("", text)
    problems = [f"{name}: a command: nalvera {' '.join(c)}" for c in commands_in(clean)
                if c and c[0] in subparsers()]
    problems += [f"{name}: an option: {m}" for m in re.findall(r"(?<![\w-])--[a-z][a-z-]*",
                                                                clean)]
    return problems


def command_line_text_problems(name: str, text: str) -> List[str]:
    """A command-line example holds no Python call of the package."""
    return [f"{name}: a Python call: {m}" for m in _PY_CALL_RX.findall(text)]


#: The login cell of the notebooks, with placeholders a test replaces.
NOTEBOOK_LOGIN = 'nalvera.login("you@university.org", "nvk_...")'


def notebook_script(path: Path, email: str, key: str) -> str:
    """A notebook's code cells as one script, signed in as ``email``."""
    code, _cells = notebook_code(path)
    assert NOTEBOOK_LOGIN in code, path.name
    return code.replace(NOTEBOOK_LOGIN, f"nalvera.login({email!r}, {key!r})")


def notebook_code(path: Path) -> Tuple[str, List[Dict[str, Any]]]:
    """The code cells of a notebook joined into one script, and every cell."""
    data = json.loads(path.read_text(encoding="utf-8"))
    cells = data.get("cells") or []
    code = "\n\n".join("".join(c.get("source") or []) for c in cells
                       if c.get("cell_type") == "code")
    return code + "\n", cells


# ── The generated files ───────────────────────────────────────────────────────
def _help(action: argparse.Action) -> str:
    return (action.help or "").replace("%%", "%")


def _required(action: argparse.Action) -> bool:
    """Whether an option or argument must be given. argparse's own flag for
    a positional with nargs="*" differs between Python versions."""
    if action.option_strings:
        return bool(action.required)
    return action.nargs not in ("*", "?")


def _usage(name: str, sub: argparse.ArgumentParser) -> str:
    parts = [f"nalvera {name}"]
    for action in sub._actions:
        if not action.option_strings and action.dest != "help":
            parts.append(f"{action.metavar}..." if action.nargs in ("+", "*") else action.metavar)
        elif _required(action):
            parts.append(f"{action.option_strings[0]} {action.metavar}")
    return " ".join(parts)


def cheatsheet() -> str:
    """examples/cli_cheatsheet.md: every command and option, one line each."""
    from nalvera import cli, messages
    top = parser()
    lines = ["# The nalvera command line: every command and option", "",
             "Generated from the package's own parser by `tests/examples_helpers.py`; a test "
             "fails when this file is out of date. `nalvera run --help`, and the same for each "
             "command, shows it in the terminal.",
             "", "- `nalvera --help`: " + messages.text("help.help"),
             "- `nalvera --version`: " + messages.text("help.version")]
    for name, sub in subparsers(top).items():
        lines += ["", f"## `{_usage(name, sub)}`", "", sub.description or ""]
        actions = [a for a in sub._actions if not isinstance(a, argparse._HelpAction)]
        if actions:
            lines.append("")
