def quoted_lines(path: str, first: Optional[str], last: Optional[str]) -> str:
    """The text a quote marker names: the whole file, or its lines
    ``first``..``last`` (1-based, inclusive)."""
    lines = (ROOT / path).read_text(encoding="utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if first is None:
        return "\n".join(lines)
    assert 1 <= int(first) <= int(last) <= len(lines), (path, first, last, len(lines))
    return "\n".join(lines[int(first) - 1:int(last)])


def rewrite_readme(readme: str) -> str:
    """README.md with every marked quote and generated table rebuilt."""
    def quote(match: re.Match[str]) -> str:
        body = quoted_lines(match.group("path"), match.group("first"), match.group("last"))
        head = match.group(0)[:match.start("body") - match.start(0)]
        return f"{head}{body}\n```"

    readme = QUOTE_RX.sub(quote, readme)
    tables = readme_tables(readme)

    def table(match: re.Match[str]) -> str:
        name = match.group("name")
        if name not in tables:
            return match.group(0)
        return f"[//]: # (generated: {name})\n\n{tables[name]}\n\n[//]: # (end: {name})"

    return TABLE_RX.sub(table, readme)


