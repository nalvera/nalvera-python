def signature_text(function: Callable, name: str) -> str:
    """``name(a, b=None, *, c=False, **options)`` from ``inspect.signature``."""
    parts, star = [], False
    for parameter in inspect.signature(function).parameters.values():
        if parameter.name == "self":
            continue
        if parameter.kind is parameter.VAR_KEYWORD:
            parts.append(f"**{parameter.name}")
            continue
        if parameter.kind is parameter.KEYWORD_ONLY and not star:
            parts.append("*")
            star = True
        parts.append(parameter.name if parameter.default is parameter.empty
                     else f"{parameter.name}={parameter.default!r}")
    return f"{name}({', '.join(parts)})"


