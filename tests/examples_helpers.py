def _default_text(name: str, defaults: Dict[str, Any]) -> str:
    """The default(s) of an argument; where the functions differ, each value
    with the functions that have it."""
    groups: Dict[str, List[str]] = {}
    for function, value in defaults.items():
        shown = "required" if value is inspect.Parameter.empty else f"`{value!r}`"
        groups.setdefault(shown, []).append(function)
    meaning = MEANING.get(name, "")
    parts = []
